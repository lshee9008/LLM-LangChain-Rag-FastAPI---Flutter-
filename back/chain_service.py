# =========================================================
# 1. LLM과 Retriever 준비
# =========================================================


# ---------------------------------------------------------
# OpenAI LLM 객체 생성
# ---------------------------------------------------------
#
# model="gpt-4o-mini"
# → 사용할 OpenAI 모델
#
# temperature=0.3
# → 답변의 랜덤성 정도
#
# 0에 가까울수록:
# 안정적 / 일관된 답변
#
# 높을수록:
# 창의적 / 다양한 답변
#
# RAG에서는 사실 기반 답변이 중요하므로
# 0 ~ 0.3 정도를 많이 사용함
# ---------------------------------------------------------
llm = ChatOpenAI(
    model="gpt-4o-mini",
    temperature=0.3
)


# ---------------------------------------------------------
# 첼시 Vector DB의 Retriever 가져오기
# ---------------------------------------------------------
#
# 이전 rag_service.py에서
#
# return vectorstore.as_retriever(
#     search_kwargs={"k": 3}
# )
#
# 로 만들었던 Retriever
#
# 따라서 질문이 들어오면
# 관련 문서 Top 3를 반환하게 된다.
# ---------------------------------------------------------
retriever = get_chelsea_retriever()



# =========================================================
# 2. 세션별 대화 히스토리 저장소
# =========================================================


# ---------------------------------------------------------
# 사용자마다 서로 다른 대화를 유지하기 위한 Dictionary
# ---------------------------------------------------------
#
# 예:
#
# {
#     "user1": user1의 대화 기록,
#     "user2": user2의 대화 기록,
#     "abc123": abc123 사용자의 대화 기록
# }
#
# session_id를 key로 사용한다.
#
# 중요한 점:
#
# 현재는 Python 메모리에 저장되기 때문에
# FastAPI 서버를 종료하면 대화 기록이 전부 사라진다.
#
# 실제 서비스에서는 Redis / DB 등을 사용할 수 있다.
# ---------------------------------------------------------
user_session_store = {}



def get_session_history(session_id: str):
    """
    session_id에 해당하는 사용자의
    대화 History 객체를 가져오는 함수

    만약 해당 사용자의 대화가 아직 없다면
    새로운 InMemoryChatMessageHistory를 생성한다.

    Parameters
    ----------
    session_id : str
        사용자를 구분하기 위한 세션 ID

    Returns
    -------
    InMemoryChatMessageHistory
        해당 세션의 대화 기록
    """

    # -----------------------------------------------------
    # 아직 해당 session_id의 History가 없다면
    # 새로운 메모리 객체 생성
    # -----------------------------------------------------
    #
    # 예:
    #
    # 첫 요청
    #
    # session_id = "user1"
    #
    # user_session_store에 "user1" 없음
    #
    # ↓
    #
    # {
    #     "user1": InMemoryChatMessageHistory()
    # }
    #
    # 생성
    # -----------------------------------------------------
    if session_id not in user_session_store:
        user_session_store[session_id] = (
            InMemoryChatMessageHistory()
        )

    # -----------------------------------------------------
    # 해당 사용자의 대화 History 반환
    # -----------------------------------------------------
    return user_session_store[session_id]



# =========================================================
# 3. 대화 맥락을 이용한 검색 질문 재작성
# =========================================================


# ---------------------------------------------------------
# 이 부분이 "History-Aware Retriever"의 핵심
# ---------------------------------------------------------
#
# RAG에서 단순히 현재 질문만 검색하면
# 문제가 발생할 수 있다.
#
# 예:
#
# 사용자:
# "첼시의 홈구장은 어디야?"
#
# AI:
# "스탬퍼드 브리지입니다."
#
# 사용자:
# "그 경기장은 언제 지어졌어?"
#
#
# 두 번째 질문만 보면:
#
# "그 경기장은 언제 지어졌어?"
#
# 어떤 경기장인지 알 수 없다.
#
#
# 따라서 이전 대화를 참고하여
#
# "첼시의 홈구장인 스탬퍼드 브리지는 언제 지어졌어?"
#
# 처럼 독립적인 검색 질문으로 변환한다.
# ---------------------------------------------------------
contextualize_q_prompt = ChatPromptTemplate.from_messages([

    # -----------------------------------------------------
    # System Prompt
    # -----------------------------------------------------
    # LLM에게 역할을 부여
    #
    # "답변하지 말고 검색하기 좋은 독립적인 질문으로 바꿔라"
    # 라는 역할
    # -----------------------------------------------------
    (
        "system",
        """
        이전 대화 내용과 최근 사용자 질문을 바탕으로,
        검색엔진에 사용할 수 있는 독립적인 질문으로 재구성하세요.
        """
    ),

    # -----------------------------------------------------
    # 기존 대화 기록 삽입
    # -----------------------------------------------------
    #
    # chat_history 안에는 예를 들어:
    #
    # HumanMessage("첼시 홈구장이 어디야?")
    # AIMessage("스탬퍼드 브리지입니다.")
    #
    # 같은 기록이 들어간다.
    # -----------------------------------------------------
    MessagesPlaceholder("chat_history"),

    # -----------------------------------------------------
    # 현재 사용자가 보낸 최신 질문
    # -----------------------------------------------------
    #
    # {input}
    #
    # 실행 시 실제 사용자 질문으로 치환됨
    #
    # 예:
    #
    # "그 경기장은 언제 지어졌어?"
    # -----------------------------------------------------
    (
        "human",
        "{input}"
    )
])



# ---------------------------------------------------------
# History-Aware Retriever 생성
# ---------------------------------------------------------
#
# 세 가지를 결합한다.
#
# 1. llm
# → 질문을 다시 쓰는 역할
#
# 2. retriever
# → 실제 Vector DB 검색 역할
#
# 3. contextualize_q_prompt
# → 어떤 방식으로 질문을 재작성할지 정의
#
#
# 전체 흐름:
#
# 사용자:
# "그 선수는 언제 입단했어?"
#
#        ↓
#
# 이전 대화 확인
#
#        ↓
#
# LLM이 검색용 질문 재작성
#
# "콜 파머는 첼시에 언제 입단했어?"
#
#        ↓
#
# Retriever
#
#        ↓
#
# ChromaDB 검색
# ---------------------------------------------------------
history_aware_retriever = create_history_aware_retriever(
    llm,
    retriever,
    contextualize_q_prompt
)



# =========================================================
# 4. 실제 답변을 생성하는 Prompt
# =========================================================


# ---------------------------------------------------------
# 여기서는 Retriever가 검색한 Document를 바탕으로
# 최종 답변을 생성한다.
#
#
# 검색용 Prompt
# contextualize_q_prompt
#
# 와
#
# 답변용 Prompt
# qa_prompt
#
# 는 역할이 다르다는 것이 중요하다.
# ---------------------------------------------------------
qa_prompt = ChatPromptTemplate.from_messages([

    # -----------------------------------------------------
    # 시스템 프롬프트
    # -----------------------------------------------------
    #
    # 챗봇의 페르소나와 답변 규칙 설정
    #
    # {context}
    #
    # Retriever에서 검색된 문서들이
    # 이 위치에 들어오게 된다.
    # -----------------------------------------------------
    (
        "system",
        """
        너는 첼시 FC(Chelsea FC)의 열정적이고
        박학다식한 공식 AI 챗봇
        '블루스 봇(Blues Bot)'이야.

        아래 제공된 [구단 정보 문맥]을
        우선적으로 바탕으로 질문에 답변해줘.

        문맥에 없는 내용이라도
        일반적인 첼시 구단 지식이 있다면
        친절하게 설명해줘.

        모르는 내용은 확실히 모른다고 말하고,
        첼시 팬들에게 친근하게
        'Keep The Blue Flag Flying High!'
        같은 인사나 분위기를 곁들여줘.


        [구단 정보 문맥]

        {context}
        """
    ),

    # -----------------------------------------------------
    # 이전 대화 History 삽입
    # -----------------------------------------------------
    #
    # 최종 답변을 생성할 때도
    # 이전 대화를 참고할 수 있도록 한다.
    #
    # 이를 통해:
    #
    # 사용자:
    # "콜 파머 알려줘"
    #
    # AI:
    # "콜 파머는 ..."
    #
    # 사용자:
    # "몇 살이야?"
    #
    # 같은 자연스러운 대화가 가능해진다.
    # -----------------------------------------------------
    MessagesPlaceholder("chat_history"),

    # -----------------------------------------------------
    # 현재 사용자 질문
    # -----------------------------------------------------
    (
        "human",
        "{input}"
    )
])



# =========================================================
# 5. Document → LLM 답변 Chain
# =========================================================


# ---------------------------------------------------------
# create_stuff_documents_chain
# ---------------------------------------------------------
#
# Retriever가 가져온 여러 Document를
# 하나의 context로 합친 뒤
# LLM에게 전달한다.
#
#
# 예:
#
# Retriever 검색 결과
#
# Document 1
# "첼시는 1905년에 창단되었다."
#
# Document 2
# "홈구장은 스탬퍼드 브리지이다."
#
# Document 3
# "첼시는 런던을 연고로 한다."
#
#
#              ↓
#
# 하나의 Context
#
# """
# 첼시는 1905년에 창단되었다.
# 홈구장은 스탬퍼드 브리지이다.
# 첼시는 런던을 연고로 한다.
# """
#
#              ↓
#
# qa_prompt의
#
# {context}
#
# 위치에 삽입
#
#              ↓
#
# LLM 답변 생성
# ---------------------------------------------------------
question_answer_chain = create_stuff_documents_chain(
    llm,
    qa_prompt
)



# =========================================================
# 6. Retriever + Answer Chain 연결
# =========================================================


# ---------------------------------------------------------
# RAG 전체 기본 Chain 생성
# ---------------------------------------------------------
#
# history_aware_retriever
#
# 역할:
#
# 대화 History 확인
#       ↓
# 검색 질문 재작성
#       ↓
# Vector DB 검색
#
#
# question_answer_chain
#
# 역할:
#
# 검색된 Document
#       ↓
# Prompt Context 삽입
#       ↓
# LLM 답변
#
#
# 둘을 연결하면:
#
# 질문
# ↓
# 검색
# ↓
# 문서
# ↓
# LLM
# ↓
# 답변
#
# 형태의 완전한 RAG Chain이 된다.
# ---------------------------------------------------------
base_rag_chain = create_retrieval_chain(
    history_aware_retriever,
    question_answer_chain
)



# =========================================================
# 7. RAG + 대화 Memory 통합
# =========================================================


# ---------------------------------------------------------
# RunnableWithMessageHistory
# ---------------------------------------------------------
#
# 지금까지 만든 base_rag_chain에는
# RAG 기능은 있지만
#
# "어떤 사용자가 어떤 대화를 했는지"
#
# 관리하는 기능을 Wrapper로 추가한다.
#
#
# 전체 구조:
#
#             사용자
#                │
#                ▼
#          session_id 확인
#                │
#                ▼
#        이전 History 가져오기
#                │
#                ▼
#       base_rag_chain 실행
#                │
#        ┌───────┴───────┐
#        ▼               ▼
# 질문 재작성          답변 생성
#        │
#        ▼
# Vector DB 검색
#        │
#        ▼
#      Context
#        │
#        └───────► LLM
#                   │
#                   ▼
#                 답변
#                   │
#                   ▼
#          History에 저장
# ---------------------------------------------------------
chelsea_chat_chain = RunnableWithMessageHistory(

    # -----------------------------------------------------
    # Memory를 적용할 대상 Chain
    # -----------------------------------------------------
    base_rag_chain,


    # -----------------------------------------------------
    # session_id를 이용해서
    # 해당 사용자의 History를 가져오는 함수
    # -----------------------------------------------------
    get_session_history,


    # -----------------------------------------------------
    # 사용자의 현재 질문이 들어있는 key
    # -----------------------------------------------------
    #
    # Chain 실행:
    #
    # {
    #     "input": "첼시 홈구장이 어디야?"
    # }
    #
    # 여기서 "input"을 의미
    # -----------------------------------------------------
    input_message_key="input",


    # -----------------------------------------------------
    # 이전 대화 기록이 들어갈 key
    # -----------------------------------------------------
    #
    # Prompt에서 사용한
    #
    # MessagesPlaceholder("chat_history")
    #
    # 와 정확하게 이름이 같아야 한다.
    # -----------------------------------------------------
    history_messages_key="chat_history",


    # -----------------------------------------------------
    # AI의 최종 답변이 들어있는 key
    # -----------------------------------------------------
    #
    # create_retrieval_chain()의 결과는
    # 일반적으로 다음과 같은 Dictionary 형태
    #
    # {
    #     "input": "...",
    #     "context": [...],
    #     "answer": "..."
    # }
    #
    # 따라서 "answer"를 AI 메시지로
    # History에 저장하도록 설정한다.
    # -----------------------------------------------------
    output_messages_key="answer"
)